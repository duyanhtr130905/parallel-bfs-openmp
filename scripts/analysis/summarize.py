"""Validate the November 24 CSV and regenerate the empirical LaTeX tables."""
import csv
import math
from collections import defaultdict
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "results/experiment-20261124/raw.csv"
OUT = ROOT / "report/generated"
ALGORITHMS = {"serial": "Serial", "omp-basic": "Basic", "omp-opt": "Optimized"}
GRAPHS = {
    "cycle2048": ("Chu trình", "Chu trình"),
    "ladder1024": ("Đồ thị thang", "Thang"),
    "grid96x64": ("Lưới", "Lưới"),
    "tree3-small": ("Cây bậc 3 nhỏ", "Cây 3 nhỏ"),
    "tree2-large": ("Cây nhị phân lớn", "Cây 2 lớn"),
    "tree4-large": ("Cây bậc 4 lớn", "Cây 4 lớn"),
}
ROUND_IDS = set(range(-2, 12))


def widths(graph, layers):
    if graph == "cycle2048":
        return [1] * layers
    if graph == "ladder1024":
        return [1] + [2] * (layers - 2) + [1]
    if graph == "grid96x64":
        return [min(63, k) - max(0, k - 95) + 1 for k in range(layers)]
    branch = int(graph[4])
    return [branch**k for k in range(layers)]


def quantile(samples, q):
    ordered = sorted(samples)
    index = q * (len(ordered) - 1)
    left = math.floor(index)
    return ordered[left] + (ordered[math.ceil(index)] - ordered[left]) * (index - left)


def load():
    samples = defaultdict(dict)
    metadata = {}
    order = defaultdict(list)
    with RAW.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            graph, algo = row["graph"], row["algorithm"]
            n, m, depth, repeat, threads = (
                int(row[name]) for name in ("vertices", "edges", "max_depth", "round", "threads")
            )
            time = Decimal(row["ms"])
            if (
                graph not in GRAPHS or algo not in ALGORITHMS or repeat not in ROUND_IDS
                or threads != (1 if algo == "serial" else 8)
                or not time.is_finite() or time <= 0 or repeat in samples[graph, algo]
                or metadata.setdefault(graph, (n, m, depth)) != (n, m, depth)
            ):
                raise ValueError(f"Unexpected measurement: {row}")
            samples[graph, algo][repeat] = time
            order[graph, repeat].append(algo)
    for graph in GRAPHS:
        n, m, depth = metadata[graph]
        layer_widths = widths(graph, depth + 1)
        expected_arcs = {
            "cycle2048": n, "ladder1024": 2 * 1023 + 1024,
            "grid96x64": 64 * 95 + 96 * 63,
        }.get(graph, n - 1)
        if sum(layer_widths) != n or m != expected_arcs or min(layer_widths) < 1:
            raise ValueError(f"Graph metadata differs from construction: {graph}")
        for algo in ALGORITHMS:
            if set(samples[graph, algo]) != ROUND_IDS:
                raise ValueError(f"Incomplete measurements: {graph}, {algo}")
        for repeat in ROUND_IDS:
            algos = list(ALGORITHMS)
            shift = (repeat + 2) % 3
            if order[graph, repeat] != algos[shift:] + algos[:shift]:
                raise ValueError(f"Unexpected order: {graph}, round {repeat}")
    stats = {
        key: tuple(quantile([times[r] for r in range(12)], Decimal(q))
                   for q in ("0.25", "0.5", "0.75"))
        for key, times in samples.items()
    }
    return metadata, samples, stats


def num(value, digits=4):
    return str(value.quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_UP))


def speed(value):
    return f"{value:.2e}" if value < Decimal("0.01") else num(value, 4)


def table(name, rows):
    (OUT / f"{name}.tex").write_text(
        "% Generated by scripts/analysis/summarize.py\n"
        + "\n".join(" & ".join(row) + r" \\" for row in rows) + "\n\\bottomrule\n",
        encoding="utf-8",
    )


def generate():
    metadata, samples, stats = load()
    OUT.mkdir(parents=True, exist_ok=True)
    graph_rows, main_rows, detail, per_level, sensitivity, overview = ([] for _ in range(6))
    for graph, (label, short) in GRAPHS.items():
        n, m, d = metadata[graph]
        layer_widths = widths(graph, d + 1)
        shuffled = {"tree3-small": "71", "tree2-large": "2026", "tree4-large": "83"}.get(graph)
        graph_rows.append((short, str(n), str(m), str(d), str(d + 1),
                           num(Decimal(n) / (d + 1), 2), str(max(layer_widths)),
                           f"Xáo ({shuffled})" if shuffled else "Theo cấu trúc"))
        med = {algo: stats[graph, algo][1] for algo in ALGORITHMS}
        winner = min(med, key=med.get)
        fastest_omp = min(("omp-basic", "omp-opt"), key=med.get)
        for algo, display in ALGORITHMS.items():
            q1, median, q3 = stats[graph, algo]
            ratio = med["serial"] / median
            value = num(median)
            main_rows.append((
                short if algo == "serial" else "", display,
                rf"\bfseries {value}" if algo == winner else value,
                rf"[\num{{{num(q1)}}}\,\textup{{;}}\,\num{{{num(q3)}}}]",
                speed(ratio) if algo != "serial" else "{}",
                num(100 * ratio / 8) if algo != "serial" else "{}",
                num(1 / ratio, 2) if ratio < 1 else "{}",
            ))
            detail.append((short if algo == "serial" else "", display,
                           *(num(v, 5) for v in (q1, median, q3, q3 - q1,
                                                 min(samples[graph, algo][r] for r in range(12)),
                                                 max(samples[graph, algo][r] for r in range(12))))))
        if graph in ("cycle2048", "ladder1024", "grid96x64"):
            basic, opt = med["omp-basic"], med["omp-opt"]
            per_level.append((label, str(d + 1), num(basic / (d + 1), 3),
                              num(opt / (d + 1), 3), num(opt / basic, 3)))
        if graph in ("tree2-large", "tree4-large"):
            for algo in ("omp-basic", "omp-opt"):
                sensitivity.append((label if algo == "omp-basic" else "", ALGORITHMS[algo],
                                    *(num(q / med[algo], 3) for q in stats[graph, "serial"])))
        descriptors = {
            "cycle2048": "Mỗi tầng có một đỉnh",
            "ladder1024": "Nhiều tầng, tối đa hai đỉnh mỗi tầng",
            "grid96x64": "Bề rộng lớn nhất theo đường chéo",
            "tree3-small": "Ít tầng, tổng số đỉnh nhỏ hơn hai cây lớn",
            "tree2-large": "Tầng lá rộng, Serial phân tán mạnh",
            "tree4-large": "Tầng lá rộng, chỉ Optimized thắng Serial",
        }
        overview.append((short, ALGORITHMS[winner], ALGORITHMS[fastest_omp],
                         speed(med["serial"] / med[fastest_omp]), descriptors[graph]))
    for name, rows in (
        ("graphs", graph_rows), ("main-results", main_rows), ("quartiles", detail),
        ("per-level", per_level), ("sensitivity", sensitivity), ("overview", overview),
    ):
        table(name, rows)


if __name__ == "__main__":
    generate()

